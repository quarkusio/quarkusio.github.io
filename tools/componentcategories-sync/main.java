import java.io.File;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.Callable;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.PropertyNamingStrategies;
import com.fasterxml.jackson.dataformat.yaml.YAMLGenerator;
import com.fasterxml.jackson.dataformat.yaml.YAMLMapper;

import io.quarkus.bootstrap.resolver.maven.MavenArtifactResolver;
import io.quarkusio.categories.ComponentCategories;
import io.quarkusio.categories.sync.CategoryAssignment;
import io.quarkusio.categories.sync.DependencyGraph;
import io.quarkusio.categories.sync.PlatformDescriptor;
import picocli.CommandLine;

/**
 * Keeps _data/componentcategories.yaml current: the platform extension categories of every component of the Quarkus
 * platform. The work is in PlatformDescriptor (the platform's extensions and categories), DependencyGraph (Maven)
 * and CategoryAssignment (the rules); this script writes the file, whose shape is the website's ComponentCategories.
 */
@CommandLine.Command(name = "sync-componentcategories", mixinStandardHelpOptions = true)
public class main implements Callable<Integer> {

    static final String HEADER = "# Generated by tools/componentcategories-sync. Do not edit: changes are overwritten.\n";

    @CommandLine.Option(names = "--output", description = "The file to write (env COMPONENTCATEGORIES_OUTPUT)")
    File output = new File(env("COMPONENTCATEGORIES_OUTPUT", "_data/componentcategories.yaml"));

    @CommandLine.Option(names = "--platform", description = "The platform version (env PLATFORM_VERSION; default the registry's recommended one)")
    String platformVersion = env("PLATFORM_VERSION", null);

    static String env(String name, String fallback) {
        String value = System.getenv(name);
        return value == null || value.isBlank() ? fallback : value;
    }

    public static void main(String[] args) {
        System.exit(new CommandLine(new main()).execute(args));
    }

    @Override
    public Integer call() throws Exception {
        MavenArtifactResolver resolver = MavenArtifactResolver.builder().setWorkspaceDiscovery(false)
                .setArtifactTransferLogging(false).build();
        String version = platformVersion != null ? platformVersion : PlatformDescriptor.recommendedVersion(resolver);

        PlatformDescriptor.Platform platform = PlatformDescriptor.platform(PlatformDescriptor.resolve(resolver, version));
        System.out.printf("Platform %s: %d extensions, %d categories%n", platform.version(),
                platform.extensions().size(), platform.categories().size());

        List<String> problems = new ArrayList<>();
        Map<String, Set<String>> dependencies = DependencyGraph.of(resolver, platform.extensions(), problems::add);
        problems.forEach(p -> System.err.println("WARNING: " + p));
        if (problems.size() > platform.extensions().size() / 10) {
            System.err.println("Too many extensions could not be resolved; refusing to write incomplete data");
            return 1;
        }

        ComponentCategories result = CategoryAssignment.assign(platform, dependencies);
        String yaml = HEADER + yaml().writeValueAsString(result);

        if (output.exists() && Files.readString(output.toPath()).equals(yaml)) {
            System.out.println("No changes: " + output.getPath() + " is up to date");
            return 0;
        }
        Files.writeString(output.toPath(), yaml);
        System.out.printf("Written %s: %d components%n", output.getPath(), result.components().size());
        return 0;
    }

    static ObjectMapper yaml() {
        return YAMLMapper.builder().propertyNamingStrategy(PropertyNamingStrategies.SNAKE_CASE)
                .disable(YAMLGenerator.Feature.WRITE_DOC_START_MARKER)
                .enable(YAMLGenerator.Feature.MINIMIZE_QUOTES)
                .enable(YAMLGenerator.Feature.INDENT_ARRAYS_WITH_INDICATOR).build();
    }
}
